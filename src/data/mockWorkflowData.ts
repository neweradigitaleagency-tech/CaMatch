export function seedWorkflowData(requestId?: string): void {
  const rid = requestId || "demo_request_plomberie";

  const requestStore = useRequestStore.getState();
  const matchingStore = useMatchingStore.getState();
  const chatStore = useChatStore.getState();
  const escrowStore = useEscrowStore.getState();
  const proStore = useProStore.getState();

  const existingRequest = requestStore.requests.find((r) => r.id === rid);
  if (!existingRequest) {
    requestStore.addRequest({ ...MOCK_WORKFLOW_REQUEST, id: rid });
  }

  const proposals = generateMockProposals(rid);
  matchingStore.setProposals({ ...matchingStore.proposals, [rid]: proposals });
  matchingStore.setSearching(null);

  const existingConv = chatStore.conversations.find((c) => c.id === "demo_conv_1");
  if (!existingConv) {
    chatStore.upsertConversation(MOCK_WORKFLOW_CONVERSATION);
    chatStore.appendMessages("demo_conv_1", MOCK_WORKFLOW_MESSAGES);
  }

  const existingMission = requestStore.missions.find((m) => m.id === "demo_mission_1");
  if (!existingMission) {
    requestStore.addMission(MOCK_WORKFLOW_MISSION);
  }

  const existingEscrow = escrowStore.entries.find((e) => e.missionId === "demo_mission_1");
  if (!existingEscrow) {
    escrowStore.addEntry(MOCK_WORKFLOW_ESCROW);
  }

  const existingProJob = proStore.jobs.find((j) => j.id === "demo_mission_1");
  if (!existingProJob) {
    proStore.addJob({
      id: "demo_mission_1",
      clientId: "client_marie",
      clientName: "Marie K.",
      clientPhone: "+225 01 02 03 04",
      clientAvatarUrl: undefined,
      clientLocation: "Cocody Riviera 3, Abidjan",
      category: "maison-reparations",
      serviceName: "Plomberie",
      description: "Fuite d'eau sous l'évier cuisine",
      status: "in_progress",
      travelFeeXOF: 0,
      laborFeeXOF: 25000,
      totalFeeXOF: 43500,
      createdAt: new Date(NOW.getTime() - DAY).toISOString(),
      scheduledDate: new Date(NOW.getTime()).toISOString().split("T")[0],
      scheduledTime: "14:00",
      pricingModel: "fixed",
      beforePhoto: "https://images.unsplash.com/photo-1585704032915-c3400ca199e7?w=400&h=300&fit=crop",
      afterPhoto: "https://images.unsplash.com/photo-1616627547584-bf28cee262db?w=400&h=300&fit=crop",
    });
  }
}

