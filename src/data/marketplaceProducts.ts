export function getProductById(id: string): Product | undefined {
  return MARKETPLACE_PRODUCTS.find((p) => p.id === id)
}

export function getProductsByVertical(vertical: string): Product[] {
  return MARKETPLACE_PRODUCTS.filter((p) => p.vertical === vertical)
}

export function getProductsBySeller(sellerId: string): Product[] {
  return MARKETPLACE_PRODUCTS.filter((p) => p.sellerId === sellerId)
}

export function getProductsByCategory(categoryId: string): Product[] {
  return MARKETPLACE_PRODUCTS.filter((p) => {
    const catSlug = categoryId.replace(/^ps-|^sh-|^re-/, "")
    return p.subcategory.includes(catSlug) || p.category.includes(catSlug)
  })
}

export function searchProducts(query: string): Product[] {
  const q = query.toLowerCase()
  return MARKETPLACE_PRODUCTS.filter(
    (p) => p.name.toLowerCase().includes(q) || p.description.toLowerCase().includes(q) || p.category.toLowerCase().includes(q),
  )
}
